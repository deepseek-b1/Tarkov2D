MAP_W, MAP_H = 60, 44


def _grid():
    return [["." for _ in range(MAP_W)] for _ in range(MAP_H)]


def _helpers(g):
    def put(x, y, c):
        if 0 <= x < MAP_W and 0 <= y < MAP_H:
            g[y][x] = c

    def hline(x1, x2, y, c):
        for x in range(x1, x2 + 1):
            put(x, y, c)

    def vline(x, y1, y2, c):
        for y in range(y1, y2 + 1):
            put(x, y, c)

    def outline(x1, y1, x2, y2, c="#"):
        hline(x1, x2, y1, c)
        hline(x1, x2, y2, c)
        vline(x1, y1 + 1, y2 - 1, c)
        vline(x2, y1 + 1, y2 - 1, c)

    def fill(x1, y1, x2, y2, c):
        for y in range(y1, y2 + 1):
            for x in range(x1, x2 + 1):
                put(x, y, c)

    return put, hline, vline, outline, fill


